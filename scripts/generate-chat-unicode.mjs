#!/usr/bin/env node
// Offline deterministic generation. --download is the only network-enabled mode.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const directory = 'scripts/data/unicode/17.0.0';
const sources = {
  'GraphemeBreakProperty.txt': 'https://www.unicode.org/Public/17.0.0/ucd/auxiliary/GraphemeBreakProperty.txt',
  'DerivedCoreProperties.txt': 'https://www.unicode.org/Public/17.0.0/ucd/DerivedCoreProperties.txt',
  'emoji-data.txt': 'https://www.unicode.org/Public/17.0.0/ucd/emoji/emoji-data.txt',
  'PropList.txt': 'https://www.unicode.org/Public/17.0.0/ucd/PropList.txt',
  'GraphemeBreakTest.txt': 'https://www.unicode.org/Public/17.0.0/ucd/auxiliary/GraphemeBreakTest.txt',
  'LICENSE.txt': 'https://www.unicode.org/license.txt',
};
const args = new Set(process.argv.slice(2));
if ([...args].some((arg) => !['--download', '--write', '--check'].includes(arg)) ||
    args.has('--write') === args.has('--check') || args.has('--download') && !args.has('--write')) {
  throw new Error('Usage: node scripts/generate-chat-unicode.mjs [--download] --write | --check');
}
const read = (name) => readFile(path.join(root, name), 'utf8');
async function write(name, data) {
  await mkdir(path.dirname(path.join(root, name)), { recursive: true });
  await writeFile(path.join(root, name), data);
}
const hash = (text) => createHash('sha256').update(text).digest('hex');
let manifest;
try { manifest = JSON.parse(await read(`${directory}/sources.json`)); }
catch (error) { if (error.code !== 'ENOENT') throw error; }
if (args.has('--download')) {
  const downloaded = await Promise.all(Object.entries(sources).map(async ([name, url]) => {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`Unicode download failed (${response.status}): ${name}`);
    const text = await response.text();
    if (manifest && manifest.files[name]?.sha256 !== hash(text)) {
      throw new Error(`Pinned Unicode source changed: ${name}. Review explicitly; refusing overwrite.`);
    }
    return { name, url, text, sha256: hash(text) };
  }));
  manifest = { unicode: '17.0.0', uax29Revision: 47, files: {} };
  for (const { name, url, text, sha256 } of downloaded) {
    await write(`${directory}/${name}`, text);
    manifest.files[name] = { url, sha256 };
  }
  await write(`${directory}/sources.json`, JSON.stringify(manifest, null, 2) + '\n');
}
if (!manifest || manifest.unicode !== '17.0.0' || manifest.uax29Revision !== 47) {
  throw new Error('Missing/incorrect pinned Unicode manifest; use --download --write.');
}
const files = {};
for (const [name, url] of Object.entries(sources)) {
  files[name] = await read(`${directory}/${name}`);
  if (manifest.files[name]?.url !== url || manifest.files[name]?.sha256 !== hash(files[name])) {
    throw new Error(`Pinned Unicode source mismatch: ${name}`);
  }
}

function records(text) {
  return text.split(/\r?\n/).map((line) => line.split('#')[0].trim()).filter(Boolean).map((line) => {
    const [range, ...properties] = line.split(';').map((value) => value.trim());
    const [start, end = start] = range.split('..').map((value) => parseInt(value, 16));
    return { start, end, properties };
  });
}
// Build a disjoint, fully specified property map, then compact adjacent equals.
const properties = new Uint16Array(0x110000);
const classes = { CR: 1, LF: 2, Control: 3, Extend: 4, ZWJ: 5, Regional_Indicator: 6, Prepend: 7, SpacingMark: 8, L: 9, V: 10, T: 11, LV: 12, LVT: 13 };
for (const { start, end, properties: [gcb] } of records(files['GraphemeBreakProperty.txt'])) {
  if (!(gcb in classes)) throw new Error(`Unknown GCB: ${gcb}`);
  properties.fill(classes[gcb], start, end + 1);
}
for (const { start, end, properties: [key, value] } of records(files['DerivedCoreProperties.txt'])) {
  if (key !== 'InCB') continue;
  const flag = { Consonant: 16, Linker: 32, Extend: 48 }[value];
  if (!flag) throw new Error(`Unknown InCB: ${value}`);
  for (let cp = start; cp <= end; cp += 1) properties[cp] |= flag;
}
for (const [name, key, flag] of [['emoji-data.txt', 'Extended_Pictographic', 64], ['PropList.txt', 'White_Space', 128]]) {
  for (const { start, end, properties: [property] } of records(files[name])) {
    if (property === key) for (let cp = start; cp <= end; cp += 1) properties[cp] |= flag;
  }
}
const ranges = [];
for (let start = 0; start < properties.length;) {
  let end = start;
  while (end + 1 < properties.length && properties[end + 1] === properties[start]) end += 1;
  ranges.push([start, end, properties[start]]);
  start = end + 1;
}

const header = '// Generated by scripts/generate-chat-unicode.mjs; Unicode 17.0.0 / UAX #29 rev 47.\n// Data license: scripts/data/unicode/17.0.0/LICENSE.txt.\n';
const tsData = header + `const ranges: readonly (readonly [number, number, number])[] = [\n${ranges.filter((r) => r[2]).map((r) => `  [${r.join(', ')}],`).join('\n')}\n];

/** GCB low nibble; InCB bits 4–5; Extended_Pictographic bit 6; White_Space bit 7. */
export function chatUnicodeProperty(cp: number): number {
  let lo = 0;
  let hi = ranges.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >>> 1;
    const [start, end, value] = ranges[mid];
    if (cp < start) hi = mid - 1;
    else if (cp > end) lo = mid + 1;
    else return value;
  }
  return 0;
}
`;
// A balanced CASE tree gives O(log ranges) lookup without database tables,
// mutable search_path, locale, server Unicode/ICU version, or regex properties.
function sqlTree(lo, hi) {
  if (lo === hi) return String(ranges[lo][2]);
  const mid = (lo + hi) >>> 1;
  return `(case when cp < ${ranges[mid + 1][0]} then ${sqlTree(lo, mid)} else ${sqlTree(mid + 1, hi)} end)`;
}
const textTemplate = await read('scripts/lib/chat-text.ts.template');
const sqlTemplate = await read('scripts/lib/chat-text.sql.template');
const corpus = [];
for (const [index, line] of files['GraphemeBreakTest.txt'].split(/\r?\n/).entries()) {
  const tokens = line.split('#')[0].trim().split(/\s+/);
  if (!tokens[0]) continue;
  const points = [];
  const breaks = [];
  for (const token of tokens) {
    if (token === '÷') breaks.push(points.length);
    else if (token !== '×') points.push(parseInt(token, 16));
  }
  corpus.push({ line: index + 1, points, breaks });
}
const sqlCases = '-- Generated from official Unicode 17.0.0 GraphemeBreakTest.txt.\n' +
  'create temporary table chat_grapheme_cases(source_line integer, points integer[], breaks integer[]) on commit drop;\n' +
  'insert into chat_grapheme_cases values\n' + corpus.map(({ line, points, breaks }) => {
    return `(${line}, array[${points.join(',')}], array[${breaks.join(',')}])`;
  }).join(',\n') + ';\n';
const outputs = {
  'app/src/messages/unicode.generated.ts': tsData,
  'supabase/functions/_shared/chat-unicode.generated.ts': tsData,
  'app/src/messages/text.ts': textTemplate.replace('UNICODE_MODULE', 'unicode.generated'),
  'supabase/functions/_shared/chat-text.ts': textTemplate.replace('UNICODE_MODULE', 'chat-unicode.generated.ts'),
  'supabase/migrations/0014_chat_text.sql': sqlTemplate.replace('PROPERTY_EXPRESSION', sqlTree(0, ranges.length - 1)),
  [`${directory}/grapheme-break-tests.generated.json`]: JSON.stringify(corpus) + '\n',
  'supabase/tests/database/fixtures/chat-grapheme-break.generated.inc': sqlCases,
};
let mismatches = 0;
for (const [name, content] of Object.entries(outputs)) {
  if (args.has('--write')) await write(name, content);
  else {
    let actual;
    try { actual = await read(name); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (actual !== content) { console.error(`Generated output differs: ${name}`); mismatches += 1; }
  }
}
if (mismatches) process.exitCode = 1;
else console.log(`${args.has('--write') ? 'Wrote' : 'Verified offline'} ${Object.keys(outputs).length} outputs; ${corpus.length} official conformance vectors.`);
