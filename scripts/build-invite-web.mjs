#!/usr/bin/env node
// Task 15: build the invitation web site + domain association files.
//
// Usage:
//   node scripts/build-invite-web.mjs [--out <dir>] [--test-config]
//
// Reads ALL six external inputs from the environment and FAILS when any
// is missing or malformed (this is correct behaviour — the real values
// are not part of this repository). `--test-config` switches to the
// clearly-labelled TEST-ONLY fixture (`.test` domains) so automated
// verification can run end-to-end; such output is test evidence only and
// MUST NOT be published (the site shows a badge, a TEST-ONLY-OUTPUT.txt
// marker is written, and runtime-config.js carries `testOnly: true`).
//
// Output (default `invite-web/dist/`):
//   index.html, app.js, styles.css   — copied from invite-web/
//   runtime-config.js                — GENERATED (origin, store URLs, appName)
//   apple-app-site-association       — iOS (served at the origin root)
//   .well-known/assetlinks.json      — Android app links
//
// The association files contain only public identifiers (team id, bundle
// id, package name, signing cert SHA-256) — no secrets — and must be
// hosted over HTTPS without redirects (see
// docs/operations/app-foundation-friends-ui.md for the procedures).

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  buildAppleAppSiteAssociation,
  buildAssetLinks,
  InviteWebConfigError,
  readInviteWebConfig,
  TEST_ONLY_ENV,
} from './invite-web-config.mjs';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE_SOURCE_DIR = path.join(REPO_ROOT, 'invite-web');
const DEFAULT_OUT_DIR = path.join(SITE_SOURCE_DIR, 'dist');
const APP_JSON_PATH = path.join(REPO_ROOT, 'app', 'app.json');
const STATIC_FILES = ['index.html', 'app.js', 'styles.css'];

export function usage() {
  return [
    'Usage: node scripts/build-invite-web.mjs [--out <dir>] [--test-config]',
    '',
    'Required environment variables (all six, no defaults):',
    '  INVITE_ORIGIN       HTTPS invite origin, e.g. https://invite.example.com',
    '  IOS_BUNDLE_ID       reverse-DNS iOS bundle identifier',
    '  APPLE_TEAM_ID       10-character Apple Developer Team ID',
    '  APP_STORE_ID        numeric Apple App Store id',
    '  ANDROID_PACKAGE     Android application id',
    '  ANDROID_CERT_SHA256 64-hex-digit SHA-256 of the Play signing cert',
    '                      (colons allowed)',
    '',
    '  --test-config       use the TEST-ONLY fixture (.test domains).',
    '                      Output is marked and must never be published.',
  ].join('\n');
}

/** Minimal argv parser: `--test-config`, `--out <dir>`, `--out=<dir>`. */
export function parseArgs(argv) {
  const options = { testConfig: false, out: DEFAULT_OUT_DIR, help: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--test-config') {
      options.testConfig = true;
    } else if (arg === '--help' || arg === '-h') {
      options.help = true;
    } else if (arg === '--out') {
      const value = argv[i + 1];
      if (value === undefined || value.startsWith('--')) {
        throw new Error('--out requires a directory argument');
      }
      options.out = path.resolve(REPO_ROOT, value);
      i += 1;
    } else if (arg.startsWith('--out=')) {
      options.out = path.resolve(REPO_ROOT, arg.slice('--out='.length));
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }
  return options;
}

/** Reads app.json's existing values (appName) — never invents new ones. */
export function readAppJson() {
  const raw = readFileSync(APP_JSON_PATH, 'utf8');
  const parsed = JSON.parse(raw);
  const expo = parsed?.expo;
  if (expo === undefined || expo === null || typeof expo.name !== 'string') {
    throw new Error('app/app.json has no expo.name');
  }
  return { name: expo.name, scheme: typeof expo.scheme === 'string' ? expo.scheme : '' };
}

/** `runtime-config.js` body — the ONLY generated values the page reads. */
export function renderRuntimeConfig(config, appName) {
  const body = {
    origin: config.origin,
    appName,
    iosAppStoreUrl: config.ios.appStoreUrl,
    androidPlayStoreUrl: config.android.playStoreUrl,
    testOnly: config.testOnly === true,
  };
  const banner = config.testOnly
    ? '/* GENERATED by scripts/build-invite-web.mjs --test-config — TEST ONLY. DO NOT PUBLISH. */'
    : '/* GENERATED by scripts/build-invite-web.mjs — do not edit by hand. */';
  return `${banner}\nwindow.__INVITE_RUNTIME_CONFIG__ = ${JSON.stringify(body, null, 2)};\n`;
}

/**
 * Runs the whole build. Pure enough for tests: takes an explicit env and
 * output directory, returns the files written.
 *
 * @param {{env: Record<string, string|undefined>, out: string, testConfig: boolean}} params
 */
export function buildInviteWeb({ env, out, testConfig }) {
  const source = testConfig ? TEST_ONLY_ENV : env;
  const config = readInviteWebConfig(source, { testOnly: testConfig });
  const appJson = readAppJson();

  mkdirSync(out, { recursive: true });

  const written = [];
  const write = (relativePath, contents) => {
    const target = path.join(out, relativePath);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, contents);
    written.push(relativePath);
  };

  for (const file of STATIC_FILES) {
    write(file, readFileSync(path.join(SITE_SOURCE_DIR, file)));
  }

  write('runtime-config.js', renderRuntimeConfig(config, appJson.name));
  // No trailing whitespace tricks: both files are plain JSON with a
  // newline, served verbatim (no redirects — see the operations doc).
  write(
    'apple-app-site-association',
    `${JSON.stringify(buildAppleAppSiteAssociation(config), null, 2)}\n`,
  );
  write(
    path.join('.well-known', 'assetlinks.json'),
    `${JSON.stringify(buildAssetLinks(config), null, 2)}\n`,
  );

  if (config.testOnly) {
    write(
      'TEST-ONLY-OUTPUT.txt',
      [
        'TEST-ONLY OUTPUT — DO NOT PUBLISH.',
        '',
        'Generated by `node scripts/build-invite-web.mjs --test-config` using the',
        'reserved `.test` fixture domains in scripts/invite-web-config.mjs.',
        'No real store/domain values exist in this repository; publishing this',
        'directory would break app links and point at non-existent store pages.',
        '',
      ].join('\n'),
    );
  }

  return { config, written };
}

function main(argv) {
  let options;
  try {
    options = parseArgs(argv);
  } catch (error) {
    process.stderr.write(`error: ${error instanceof Error ? error.message : String(error)}\n`);
    process.stderr.write(`${usage()}\n`);
    return 2;
  }
  if (options.help) {
    process.stdout.write(`${usage()}\n`);
    return 0;
  }

  try {
    const { config, written } = buildInviteWeb({
      env: process.env,
      out: options.out,
      testConfig: options.testConfig,
    });
    const mode = config.testOnly ? 'TEST-ONLY (do not publish)' : 'real config';
    process.stdout.write(`invite web build OK [${mode}]\n`);
    process.stdout.write(`  out:   ${options.out}\n`);
    process.stdout.write(`  origin: ${config.origin}\n`);
    process.stdout.write(`  ios:   ${config.ios.bundleId} (team ${config.ios.teamId}, store id ${config.ios.appStoreId})\n`);
    process.stdout.write(`  droid: ${config.android.package} (cert ${config.android.certSha256})\n`);
    for (const file of written) process.stdout.write(`  file:  ${file}\n`);
    return 0;
  } catch (error) {
    if (error instanceof InviteWebConfigError) {
      process.stderr.write(`error: ${error.message}\n`);
      return 1;
    }
    throw error;
  }
}

// Run only when executed directly (tests import the functions above).
const invokedDirectly =
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  process.exitCode = main(process.argv.slice(2));
}

export { main, REPO_ROOT, DEFAULT_OUT_DIR };
